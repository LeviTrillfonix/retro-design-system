#!/usr/bin/env python3
"""Build the drop-in kit for apps: design-system/dist/ (retro.css, retro.js, retro.json, example.html).

    python design-system/build/dist.py

Reads design-system/systems.json (written by build.py). Never touches styles/, tokens/ or manifest.json.
Plain Python 3, explicit UTF-8 and LF so the output is identical on Windows, macOS and Linux.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                       # design-system/
OUT = os.path.join(ROOT, 'dist')
ROLES = ['bg', 'surface', 'ink', 'muted', 'border', 'accent', 'accent2', 'highlight', 'onaccent']

def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text if text.endswith('\n') else text + '\n')

with open(os.path.join(ROOT, 'systems.json'), encoding='utf-8') as f:
    SYSTEMS = json.load(f)

# ------------------------------------------------------------------ retro.css
css = ['''/* Retro Design System: drop-in theme file for apps. Generated by design-system/build/dist.py. Do not edit.
 *
 * 1. Link this file.            <link rel="stylesheet" href="retro.css">
 * 2. Pick a system.             <body data-retro="win95">   (any element works; themes cascade to its children)
 * 3. Style with the roles.      background: var(--ui-bg); color: var(--ui-ink);
 *
 * Nine roles per system: bg surface ink muted border accent accent2 highlight onaccent
 * (onaccent = readable text on accent). Colours are the original systems' own values.
 * Ids and names: retro.json, or the table in INTEGRATE.md.
 */
''']
for s in SYSTEMS:
    r = s['resolved']
    css.append(f'/* {s["num"]:02d} {s["name"]} ({s["era"]}, {s["year"] or "n/a"}) */')
    css.append(f'[data-retro="{s["id"]}"] {{')
    for role in ROLES:
        css.append(f'  --ui-{role}: {r[role]};')
    css.append(f'  --ui-font: {s["font"]};')
    css.append(f'  --ui-size: {s["bodySize"]};')
    css.append('}')
css.append('''
/* Optional starter classes: remove if you bring your own components. They only read the roles. */
[data-retro] { background: var(--ui-bg); color: var(--ui-ink); font-family: var(--ui-font); font-size: var(--ui-size); }
.retro-panel { background: var(--ui-surface); color: var(--ui-ink); border: 2px solid var(--ui-border); padding: 16px; }
.retro-muted { color: var(--ui-muted); }
.retro-btn { font: inherit; padding: 6px 16px; background: var(--ui-surface); color: var(--ui-ink); border: 2px solid var(--ui-border); cursor: pointer; }
.retro-btn:focus-visible { outline: 2px solid var(--ui-highlight); outline-offset: 2px; }
.retro-btn--primary { background: var(--ui-accent); color: var(--ui-onaccent); border-color: var(--ui-ink); }
.retro-link { color: var(--ui-accent2); }''')
write('retro.css', '\n'.join(css))

# ------------------------------------------------------------------ retro.json
meta = [{'num': s['num'], 'id': s['id'], 'slug': s['slug'], 'name': s['name'], 'era': s['era'], 'year': s['year'],
         'tags': s['tags'], 'font': s['font'], 'bodySize': s['bodySize'], 'roles': {k: s['resolved'][k] for k in ROLES}}
        for s in SYSTEMS]
write('retro.json', json.dumps({'roles': ROLES, 'systems': meta}, indent=1, ensure_ascii=False))

# ------------------------------------------------------------------ retro.js
write('retro.js', '''/* Retro Design System: tiny switcher for retro.css. No dependencies. Generated by dist.py. Do not edit. */
(function (root) {
  "use strict";
  var SYSTEMS = ''' + json.dumps([{'id': s['id'], 'name': s['name'], 'era': s['era'], 'year': s['year']} for s in SYSTEMS],
                                  ensure_ascii=False) + ''';
  function has(id) { return SYSTEMS.some(function (s) { return s.id === id; }); }
  var Retro = {
    systems: SYSTEMS,
    /* Theme an element (default: <body>) with a system id, e.g. Retro.set("win95"). Remembers the choice if you pass { remember: true }. */
    set: function (id, el, opts) {
      if (!has(id)) throw new Error("Retro: unknown system " + id);
      (el || document.body).setAttribute("data-retro", id);
      if (opts && opts.remember) try { localStorage.setItem("retro-system", id); } catch (e) {}
      return id;
    },
    get: function (el) { return (el || document.body).getAttribute("data-retro"); },
    clear: function (el) { (el || document.body).removeAttribute("data-retro"); },
    /* Restore the remembered choice, or fall back to `fallback`. */
    restore: function (fallback, el) {
      var id = fallback;
      try { id = localStorage.getItem("retro-system") || fallback; } catch (e) {}
      return has(id) ? Retro.set(id, el) : null;
    },
    /* A <select> of all 53 systems wired to an element. */
    picker: function (target, el) {
      var sel = document.createElement("select");
      sel.setAttribute("aria-label", "Retro system");
      SYSTEMS.forEach(function (s) {
        var o = document.createElement("option");
        o.value = s.id; o.textContent = s.name + (s.year ? " (" + s.year + ")" : "");
        sel.appendChild(o);
      });
      sel.value = Retro.get(el) || SYSTEMS[0].id;
      sel.addEventListener("change", function () { Retro.set(sel.value, el, { remember: true }); });
      target.appendChild(sel);
      return sel;
    }
  };
  root.Retro = Retro;
})(this);
''')

# ------------------------------------------------------------------ example.html
write('example.html', '''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Retro kit example</title>
<link rel="stylesheet" href="retro.css">
<style>
  body { margin: 0; padding: 24px; min-height: 100vh; box-sizing: border-box; }
  .row { display: flex; flex-wrap: wrap; gap: 8px; margin-top: 16px; }
  h1 { margin: 0 0 12px; font-size: 1.4em; }
</style>
</head>
<body data-retro="win95">
  <h1>Retro kit example</h1>
  <div id="pick"></div>
  <div class="retro-panel" style="margin-top:16px;max-width:520px">
    <p>One CSS file, one attribute. Pick a system above and everything re-themes.</p>
    <p class="retro-muted">Muted text uses the <code>muted</code> role.</p>
    <div class="row">
      <button class="retro-btn">Cancel</button>
      <button class="retro-btn retro-btn--primary">OK</button>
      <a class="retro-link" href="#">A link</a>
    </div>
  </div>
  <script src="retro.js"></script>
  <script>
    Retro.restore("win95");
    Retro.picker(document.getElementById("pick"));
  </script>
</body>
</html>''')
print('dist: retro.css, retro.js, retro.json, example.html written to', OUT)

# ------------------------------------------------------------------ INTEGRATE.md
rows = '\n'.join(f'| {s["num"]:02d} | `{s["id"]}` | {s["name"]} | {s["era"]} | {s["year"] or ""} |' for s in SYSTEMS)
doc = '''# Use the Retro systems in your apps

The 53 original styles are untouched in `styles/`, `tokens/` and `manifest.json`. This guide covers the drop-in kit in `design-system/dist/`, built from those same colours. Nothing here changes the originals.

## Fastest way: one CSS file, one attribute

Copy `design-system/dist/retro.css` into your app, then:

```html
<link rel="stylesheet" href="retro.css">
<body data-retro="win95">
  <div class="retro-panel">
    <button class="retro-btn">Cancel</button>
    <button class="retro-btn retro-btn--primary">OK</button>
  </div>
</body>
```

`data-retro` works on any element, so one page can mix eras (a CRT panel inside a Windows 95 window). Open `design-system/dist/example.html` to see all 53 switch live.

In your own CSS, style with the nine roles and your components re-skin for free:

```css
.card   { background: var(--ui-surface); color: var(--ui-ink); border: 2px solid var(--ui-border); }
.card h2 { color: var(--ui-accent2); }
.cta    { background: var(--ui-accent); color: var(--ui-onaccent); }   /* onaccent is always readable on accent */
```

| Role | Use |
|---|---|
| `--ui-bg` | page / desktop ground |
| `--ui-surface` | windows, cards, inputs |
| `--ui-ink` | main text |
| `--ui-muted` | secondary text (check contrast for the systems flagged in the brand book) |
| `--ui-border` | rules, window frames |
| `--ui-accent` | primary action, title bars |
| `--ui-accent2` | links, secondary highlight |
| `--ui-highlight` | selection, focus ring |
| `--ui-onaccent` | text on `accent` |
| `--ui-font`, `--ui-size` | the system's own font stack and body size |

## Switch from JavaScript

```html
<script src="retro.js"></script>
<script>
  Retro.set("crt");                                 // theme <body>
  Retro.set("vaporwave", document.querySelector("#panel"));   // or any element
  Retro.restore("win95");                           // last remembered choice, else win95
  Retro.picker(document.querySelector("#settings"));          // a ready <select> of all 53
</script>
```

## React, Vue, Svelte, Electron, Tauri

Import `retro.css` once at the entry point and set the attribute from state:

```jsx
import "./retro.css";
export default function App({ system = "win95" }) {
  return <div data-retro={system}>...</div>;
}
```

## Python, C#, native GUIs

`retro.json` has every system's nine colours, font stack and body size, so toolkits that are not CSS (Tkinter, Qt, WPF) can read it directly:

```python
import json
ds = json.load(open("retro.json", encoding="utf-8"))
win95 = next(s for s in ds["systems"] if s["id"] == "win95")
bg, ink, accent = win95["roles"]["bg"], win95["roles"]["ink"], win95["roles"]["accent"]
```

## Fonts

Each system lists its era font first (Chicago, MS Sans Serif, Topaz and so on) then fallbacks. The era fonts are not bundled, so most machines show the fallback. Bundle fonts you have the right to ship and keep the same `--ui-font` stack.

## Accessibility

`ink` on `surface` passes WCAG AA in all 53. `muted` and `onaccent` are the originals' own colours and a few fall short of AA for small text; the table is in `contrast-report.md`. Check it before using those roles for body text.

## Ids

| # | id | System | Era | Year |
|---|---|---|---|---|
''' + rows + '''

## Rebuild

```bash
python design-system/build/build.py        # roles, tokens, brand book (writes systems.json)
python design-system/build/dist.py         # this kit
```
'''
with open(os.path.join(ROOT, 'INTEGRATE.md'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(doc)
print('INTEGRATE.md written')
